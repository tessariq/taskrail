// Command statecheck turns `taskrail repair --json` into a pass/fail gate.
// repair exits 0 on a dry run even when it finds drift, because proposing a
// diff is its job; a gate needs the opposite. This helper reads the envelope
// from stdin and fails when STATE.md has drifted from its task-file projection
// or the tree does not validate. Reading stdin rather than spawning taskrail
// keeps the Taskfile a plain pipe that Task's built-in shell runs on native
// Windows too.
package main

import (
	"encoding/json"
	"fmt"
	"io"
	"os"
	"strings"
)

func main() {
	if err := run(os.Stdin); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

type change struct {
	Field string `json:"field"`
	From  string `json:"from"`
	To    string `json:"to"`
}

// envelope mirrors only the fields of the repair machine envelope this gate
// reads. Validation is a pointer so an envelope that omits it fails loudly
// instead of reading as valid.
type envelope struct {
	Command string `json:"command"`
	Result  struct {
		Changes    []change `json:"changes"`
		BodyDiff   []string `json:"body_diff"`
		Validation *struct {
			Valid      bool     `json:"valid"`
			Violations []string `json:"violations"`
		} `json:"validation"`
	} `json:"result"`
}

const remedy = "  run 'taskrail repair --apply' and commit the regenerated planning/STATE.md;\n" +
	"  STATE.md is generated by the CLI and must never be hand-edited"

func run(in io.Reader) error {
	var env envelope
	if err := json.NewDecoder(in).Decode(&env); err != nil {
		return fmt.Errorf("statecheck: read `taskrail repair --json` output: %w", err)
	}
	if env.Command != "repair" {
		return fmt.Errorf("statecheck: expected a repair envelope on stdin, got command %q", env.Command)
	}
	result := env.Result
	if result.Validation == nil {
		return fmt.Errorf("statecheck: repair envelope carries no validation result")
	}

	var problems []string
	for _, c := range result.Changes {
		problems = append(problems, fmt.Sprintf("  %s: %q, projection says %q", c.Field, c.From, c.To))
	}
	if len(result.BodyDiff) > 0 {
		problems = append(problems, "  rendered body differs from the task files:")
		for _, line := range result.BodyDiff {
			problems = append(problems, "    "+line)
		}
	}
	if len(problems) > 0 {
		return fmt.Errorf("statecheck: planning/STATE.md has drifted from its task-file projection:\n%s\n%s",
			strings.Join(problems, "\n"), remedy)
	}

	// Checked after drift so a tree that repair can fix is reported with the
	// fix rather than with the violations the fix would clear.
	if !result.Validation.Valid {
		return fmt.Errorf("statecheck: taskrail validation fails:\n  %s\n  repair cannot fix these mechanically; run 'taskrail validate' for details",
			strings.Join(result.Validation.Violations, "\n  "))
	}
	return nil
}
